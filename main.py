print("Loading embedding model...")
embedding_function = SentenceTransformerEmbeddings(model_name="all-MiniLM-L6-v2")

def ingest_document(pdf_path, target_db):
    if not os.path.exists(pdf_path):
        return f"Error: File {pdf_path} not found."

    loader = PyPDFLoader(pdf_path)
    documents = loader.load()

    # We use different chunking strategies based on the document type
    if target_db == 'resume':
        chunk_size = 400
        chunk_overlap = 50
        persist_dir = RESUME_DB_DIR
    elif target_db == 'domain':
        chunk_size = 1000
        chunk_overlap = 150
        persist_dir = DOMAIN_DB_DIR
    else:
        return "Invalid target DB."

    text_splitter = RecursiveCharacterTextSplitter(
        chunk_size=chunk_size,
        chunk_overlap=chunk_overlap,
        separators=["\n\n", "\n", ".", " "]
    )
    chunks = text_splitter.split_documents(documents)

    # Using FAISS instead of ChromaDB
    db = FAISS.from_documents(chunks, embedding_function)
    db.save_local(persist_dir)

    print(f"✅ Successfully ingested {pdf_path} into the {target_db.upper()} database ({len(chunks)} vectors).")
    return db


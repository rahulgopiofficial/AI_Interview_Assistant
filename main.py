"""## Step 5 — Load Dataset and Apply Chat Template

The JSONL file is loaded into a HuggingFace `Dataset`. The `format_chat_template` function then converts each row's `messages` array into Llama 3's special-token format:

```
<|start_header_id|>system<|end_header_id|>  ...  <|eot_id|>
<|start_header_id|>user<|end_header_id|>    ...  <|eot_id|>
<|start_header_id|>assistant<|end_header_id|> ... <|eot_id|>
```

`add_generation_prompt=False` includes the complete assistant response in the formatted string (needed for training). At inference time this is flipped to `True` so the model generates the response rather than having it pre-supplied.

"""

# 4. Load your conversational dataset
dataset = load_dataset("json", data_files="final_training_data.jsonl", split="train")

def format_chat_template(examples):
    # This applies Llama 3's native chat template to our "messages" array
    # It converts the JSON into the exact <|start_header_id|> format Llama expects
    texts = [tokenizer.apply_chat_template(convo, tokenize=False, add_generation_prompt=False) for convo in examples["messages"]]
    return {"text": texts}

# Apply the formatting to the entire dataset
dataset = dataset.map(format_chat_template, batched=True)

"""## Step 6 — Configure the SFT Trainer

`SFTTrainer` from `trl` wraps HuggingFace's training loop for instruction fine-tuning. Key `TrainingArguments`:

| Parameter | Value | Why |
|-----------|-------|-----|
| `per_device_train_batch_size` | 2 | Max safe batch on T4 with 4-bit model |
| `gradient_accumulation_steps` | 4 | Effective batch = 8 without extra VRAM |
| `warmup_steps` | 5 | Stabilises LR ramp-up for first ~5% of steps |
| `num_train_epochs` | 1 | Sufficient for domain adaptation on 300 focused examples |
| `learning_rate` | 2e-4 | LoRA standard — adapters require higher LR than full fine-tuning (5e-5 is too slow for LoRA) |
| `bf16 / fp16` | auto | Halves activation memory; bf16 preferred for wider dynamic range |

"""


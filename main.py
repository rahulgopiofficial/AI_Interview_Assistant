"""## Step 3 — Configure LoRA

LoRA injects small trainable adapter matrices (A and B, rank `r`) into frozen model layers. Only these adapters are updated during training — roughly 0.6% of total parameters — avoiding the memory cost of full fine-tuning.

Key choices:
- **`r = 16`** — increased from the common default of 8 to give the adapter enough capacity to learn IMS-specific terminology and reasoning patterns alongside conversational style.
- **`lora_alpha = 16`** — setting alpha equal to r keeps the adapter scaling factor at 1.0 (the Unsloth recommended default).
- **All 7 target modules** (Q/K/V/O attention + gate/up/down MLP) — needed to simultaneously adapt both attention patterns and feed-forward representations for a new technical domain.
- **`use_gradient_checkpointing = "unsloth"`** — recomputes activations during backprop instead of storing them, halving VRAM usage at a ~20% compute overhead.

"""

# 3. Setup LoRA (Parameter-Efficient Fine-Tuning)

INTERVIEW_TIME_LIMIT = 15 * 60 # 15 minutes in seconds

def process_uploaded_resume(pdf_file):
    if pdf_file is None:
        return "⚠️ Please upload a PDF file."
    try:
        ingest_document(pdf_file.name, target_db="resume")
        global resume_vectorstore
        resume_vectorstore = FAISS.load_local(RESUME_DB_DIR, embedding_function, allow_dangerous_deserialization=True)
        return "✅ Resume successfully processed and loaded into active memory! You can now switch to the Interview tab."
    except Exception as e:
        return f"❌ Error processing resume: {str(e)}"

# ==========================================
# 3. CHAT & EVALUATION LOGIC
# ==========================================
def respond(user_message, history, start_time):
    """Handles the chat and checks the 15-minute timer."""
    # 1. Start the timer on the very first message
    if start_time is None:
        start_time = time.time()
        previous_question = "We are beginning the technical interview. What is your background?"
    else:
        # Check if 15 minutes have passed
        elapsed_time = time.time() - start_time
        if elapsed_time > INTERVIEW_TIME_LIMIT:
            timeout_msg = "⏳ **The 15-minute time limit has expired.** The interview is now concluded. Please click 'End Interview & Score Candidate'."
            history.append((user_message, timeout_msg))
            # Return updated history, the start time, clear the input box, and disable the input box
            return history, start_time, "", gr.update(interactive=False, placeholder="Interview Ended.")

        previous_question = history[-1][1]

    # 2. Run the RAG logic
    system_prompt = get_interviewer_response(candidate_latest_message=user_message, previous_question=previous_question)

    messages = [{"role": "system", "content": system_prompt}]
    for human_text, assistant_text in history:
        messages.append({"role": "user", "content": human_text})
        messages.append({"role": "assistant", "content": assistant_text})

    messages.append({"role": "user", "content": user_message})

    inputs = tokenizer.apply_chat_template(messages, tokenize=True, add_generation_prompt=True, return_tensors="pt").to("cuda")

    with torch.no_grad():
        outputs = model.generate(
            input_ids=inputs, max_new_tokens=150,
            eos_token_id=tokenizer.eos_token_id, pad_token_id=tokenizer.eos_token_id
        )

    response_text = tokenizer.decode(outputs[0][inputs.shape[1]:], skip_special_tokens=True)
    history.append((user_message, response_text))

    return history, start_time, "", gr.update()

def evaluate_interview(history):
    """Takes the entire chat history and asks the LLM to score the candidate."""
    if not history:
        return "No interview data to evaluate."

    # Format the transcript
    transcript = ""
    for user_msg, bot_msg in history:
        transcript += f"Candidate: {user_msg}\nInterviewer: {bot_msg}\n\n"

    # Create a new prompt telling the model to act as a recruiter grading the transcript
    eval_prompt = f"""You are a Senior Technical Recruiter. Review the following technical interview transcript.
    Evaluate the candidate's technical accuracy, depth of knowledge, and problem-solving skills.

    TRANSCRIPT:
    {transcript}

    Provide your response strictly in the following format:
    SCORE: [Give a rating from 1 to 10]
    FEEDBACK: [Provide a 2-3 sentence justification for the score]
    """

    messages = [{"role": "user", "content": eval_prompt}]
    inputs = tokenizer.apply_chat_template(messages, tokenize=True, add_generation_prompt=True, return_tensors="pt").to("cuda")

    with torch.no_grad():
        outputs = model.generate(input_ids=inputs, max_new_tokens=250, eos_token_id=tokenizer.eos_token_id, pad_token_id=tokenizer.eos_token_id)

    evaluation = tokenizer.decode(outputs[0][inputs.shape[1]:], skip_special_tokens=True)
    return evaluation

